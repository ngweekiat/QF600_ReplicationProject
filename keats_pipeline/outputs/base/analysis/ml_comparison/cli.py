TIMING='''# Training, testing and out-of-sample timing

| Item | Current behavior |
|---|---|
| Initial training return years | 2005-2014 |
| Declared validation return years | 2015-2019 |
| Headline test return years | 2020-2025 |
| Broader return-forecast OOS history | 2015-2025; this overlaps validation and test |
| Separate unseen holdout | None available after the saved test |
| Market (iteration reference only) | No ML fitting; market-cap weights updated monthly |
| Static ML | Return forecaster refitted annually on expanding past history; weights updated monthly; fixed portfolio multipliers k=1, u=1, g=0 |
| Portfolio ML | Coefficients refitted annually using past return years; variance/model-size/ridge candidates selected from cumulative past utility each December; weights updated monthly |

The models are **not frozen after 2014 or 2019**. For example, the 2020 return forecaster is fitted through December 2019 returns, while the 2021 fit includes 2020 returns. This is an expanding walk-forward backtest: a completed test year may train a later year's model. No future return from the forecast year enters that year's coefficient fit. Hyperparameter candidates are internal choices of a retained strategy, not separate reported strategies.

The nominal split does not mean every estimator has usable inputs from January 2005. The stored Portfolio ML moments begin in **February 2006 return months for both US markets** and **March 2012 for Europe**, after daily-covariance and signal-history requirements. Its first 2015 coefficient fit therefore uses February 2006-December 2014 for the US and March 2012-December 2014 for Europe. Static ML's return forecaster uses the available valid regional training observations beginning in 2005. Later fits expand each estimator's available past history through the prior return year; the European Portfolio ML history is substantially shorter initially.

Return-forecast tuning for year Y uses an earlier training segment and the trailing five available years as internal validation, then refits the selected candidate on all data through year Y-1. For the first 2015 forecast, internal training is 2005-2009, internal validation is 2010-2014, and the final refit uses 2005-2014. The schedule moves forward annually.

Static ML's portfolio recursion continues from January 2015 into the test, preserving the original non-starred strategy's inherited positions. Market and Portfolio ML test portfolios start with the original value-weighted initialization at the beginning of the test. These existing initialization conventions are retained and disclosed; this cleanup does not silently change the retained strategies' definitions.

Portfolio ML's candidate utility history begins in 2015; the first December candidate choice supports aims from 2016. The saved headline portfolio is evaluated in 2020-2025. There is no separate third dataset named OOS beyond the test: the existing OOS label denotes historical forward predictions, not an additional unseen holdout. The scripts are finite backtests, not a continuously running live service.

The saved candidate-choice table can include a prospective 2026 choice based on completed 2025 observations. No 2026 fitted return forecast, portfolio return or performance is generated by this workflow.
'''


def verify(inventory,monthly,stats,out):
    findings=[]
    def check(name,scope,passed,detail=''):
        findings.append(dict(check=name,scope=scope,status='SKIPPED' if passed is None else ('PASS' if passed else 'FAIL'),detail=detail))
    baseline_path=KEATS/'outputs/model_cleanup/original_retained_test_returns.parquet'
    baseline=pd.read_parquet(baseline_path) if baseline_path.exists() else None
    for row in inventory.itertuples():
        universe,strategy=row.universe,row.strategy
        pf=monthly.loc[(monthly.universe==universe)&(monthly.strategy==strategy)].sort_values('eom').reset_index(drop=True)
        fields=['r','tc','turnover','inv','shorting']
        if baseline is not None:
            original=baseline.loc[(baseline.universe==universe)&(baseline.type==strategy)].sort_values('eom').reset_index(drop=True)
            same=len(pf)==len(original) and pf.eom.equals(original.eom) and np.allclose(pf[fields],original[fields],rtol=1e-10,atol=1e-12)
            check('retained_strategy_matches_original',f'{universe}/{strategy}',same,'Original 72-month performance preserved within numerical tolerance')
        else:
            check('retained_strategy_matches_original',f'{universe}/{strategy}',None,'No pre-cleanup reference file in this checkout; independent accounting still runs')
        weights=pd.read_parquet(row.weights_path)
        check('weights_have_only_the_retained_method',f'{universe}/{strategy}',set(weights.type)=={strategy})
        panel=pd.read_parquet(Path(row.processed_path)/'panel.parquet',columns=['id','eom','ret_ld1','lambda'])
        wealth=pd.read_parquet(Path(row.processed_path)/'wealth.parquet').set_index('eom').wealth
        joined=weights.merge(panel,on=['id','eom'],how='left',validate='one_to_one')
        held=~joined['exit']
        complete=joined['lambda'].notna().all() and joined.loc[held,'ret_ld1'].notna().all()
        check('accounting_source_coverage',f'{universe}/{strategy}',complete)
        joined['r_i']=joined.w*joined.ret_ld1.where(held,0.)
        joined['tc_i']=.5*joined.eom.map(wealth)*joined['lambda']*(joined.w-joined.w_start)**2
        joined['turnover_i']=(joined.w-joined.w_start).abs()
        joined['inv_i']=joined.w.abs();joined['short_i']=-joined.w.clip(upper=0)
        recalculated=joined.groupby('eom').agg(r=('r_i','sum'),tc=('tc_i','sum'),turnover=('turnover_i','sum'),inv=('inv_i','sum'),shorting=('short_i','sum')).reindex(pf.eom)
        check('independent_weight_return_cost_accounting',f'{universe}/{strategy}',np.allclose(recalculated[fields],pf[fields],rtol=1e-10,atol=1e-12))
        r=pf.r.to_numpy();tc=pf.tc.to_numpy();n=len(r);mean=sum(r)/n;variance=sum((x-mean)**2 for x in r)/(n-1)
        cost=sum(tc)/n
        expected=dict(R=12*mean,TC=12*cost,R_TC=12*(mean-cost),Vol=np.sqrt(12*variance),Utility=12*(mean-cost-5*variance))
        observed=stats.loc[(stats.dataset==f'{universe}/base')&(stats.strategy==strategy)].iloc[0]
        check('independent_report_formulas',f'{universe}/{strategy}',all(np.isclose(observed[k],v,rtol=1e-11,atol=1e-11) for k,v in expected.items()))
    hash_path=KEATS/'outputs/model_cleanup/retained_input_hashes_before.csv'
    if hash_path.exists():
        for row in pd.read_csv(hash_path).itertuples():
            check('retained_input_hash_unchanged',row.path,sha256(KEATS/row.path)==row.sha256)
    else:
        check('retained_input_hash_unchanged','pre-cleanup baseline',None,'No pre-cleanup hash manifest in this checkout')
    for universe in inventory.universe.unique():
        cfg=load_config(KEATS/f'configs/{universe}/base.yaml')
        expected=json.loads((KEATS/'feature_names.json').read_text())
        check('original_50_inputs_retained',universe,len(cfg.features.names)==50 and set(cfg.features.names)==set(expected))
    result=pd.DataFrame(findings);result.to_csv(out/'independent_verification.csv',index=False)
    if result.status.eq('FAIL').any():raise AssertionError('Independent two-strategy base verification failed; inspect independent_verification.csv')
    return result


def timing_schedule(universes):
    records=[]
    for universe in universes:
        processed=load_config(KEATS/f'configs/{universe}/base.yaml').paths.processed
        folders=sorted((processed/'pfml').glob('rff_g*'))
        first_moments=[min(p.glob('????-??-??.npz')).stem for p in folders]
        if not first_moments or len(set(first_moments))!=1:raise ValueError('Default moment candidates have different history starts')
        first_return=pd.Timestamp(first_moments[0])+pd.offsets.MonthEnd(1)
        for year in range(2015,2026):
            train,full=cutoffs_for_year(year,5)
            records.append(dict(universe=universe,forecast_return_year=year,internal_training_last_return_month=train+pd.offsets.MonthEnd(1),
                internal_validation_last_return_month=full+pd.offsets.MonthEnd(1),final_refit_last_return_month=full+pd.offsets.MonthEnd(1),
                return_forecaster_first_allowed_training_return_month='2005-01-31',portfolio_ml_first_available_training_return_month=first_return,
                portfolio_ml_coefficient_last_allowed_return_year=year-1,test_year_updates_use_previously_realised_test_data=year>=2021))
    return pd.DataFrame(records)


def charts(monthly,stats,out):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    folder=out/'charts';folder.mkdir(exist_ok=True)
    for dataset,g in monthly.groupby('dataset'):
        fig,axes=plt.subplots(1,2,figsize=(12,4.5))
        for strategy,d in g.groupby('strategy'):
            d=d.sort_values('eom_ret')
            axes[0].plot(d.eom_ret,100*d.r.cumsum(),label=strategy)
            axes[1].plot(d.eom_ret,100*d.tc.cumsum(),label=strategy)
        axes[0].set(title='Cumulative gross excess returns (arithmetic)',ylabel='Percentage points')
        axes[1].set(title='Cumulative modelled trading costs',ylabel='Percentage points')
        if g.tc.max()>1:axes[1].set_yscale('symlog',linthresh=1);axes[1].set_title('Cumulative modelled trading costs (symlog)')
        for ax in axes:ax.grid(alpha=.2);ax.legend(fontsize=8)
        fig.suptitle(dataset+' | test return years 2020-2025');fig.tight_layout()
        for ext in ('png','pdf'):fig.savefig(folder/(dataset.replace('/','__')+'.'+ext),dpi=180)
        plt.close(fig)


